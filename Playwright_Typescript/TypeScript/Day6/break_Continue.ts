//break : break the loop
for(let i=1;i<10;i++)
    {  
         // console.log(i);
        if(i==5)
            {
              
                break;
            }
        console.log(i); 
    }

//continue : (jumping statement)continue without executing the current iteration
 for(let i=100;i<110;i++)
    {
         //console.log(i);
        if(i==105)
            {
               
                continue;
            }
        console.log(i);
    }